import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-surface-container/60 bg-surface-container-lowest text-on-surface shadow-card transition-all duration-300",
      interactive &&
        "hover:-translate-y-1.5 hover:shadow-card-hover hover:border-secondary/30 cursor-pointer",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

